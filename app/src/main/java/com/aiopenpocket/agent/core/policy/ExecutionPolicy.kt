package com.aiopenpocket.agent.core.policy

// @trace user-agent-builder-848153

import com.aiopenpocket.agent.core.hook.HookDecision
import com.aiopenpocket.agent.core.mcp.RiskClass
import kotlinx.serialization.json.JsonElement

/**
 * Whether a turn is allowed to touch real device/app state. [LIVE] is the default and matches every
 * behavior that existed before Task 9 — tools execute for real, gated only by [HookDecision]. [PREVIEW]
 * is for a builder test-run (Task 20): non-[RiskClass.READ] tools never execute, they report back what
 * *would* have happened (see [PolicyDecision.Simulate]) so a user can try out a draft agent without any
 * side effects. There is deliberately no third "ask every time" mode — that per-call behavior is what
 * [HookActionType.REQUIRE_APPROVAL][com.aiopenpocket.agent.core.hook.HookActionType] hooks express.
 */
enum class ExecutionMode { LIVE, PREVIEW }

/**
 * Everything the UI needs to show a human a tool call awaiting their decision, and everything
 * [ToolApprovalCoordinator] needs to route the decision back to the right run. Deliberately plain data
 * (no behavior) — [ExecutionPolicy.evaluate] only ever *constructs* one, it never resolves it.
 *
 * [runId] and [conversationId] serve different jobs: [conversationId] is what a UI uses to decide
 * whether THIS pending request belongs on screen right now (a user might have several chats with
 * pending approvals); [runId] is the narrower "may this specific caller resolve this specific request"
 * check inside [ToolApprovalCoordinator.resolve] — the same conversation can have a new run start
 * (Stop, then a fresh send) whose UI must not be able to resolve a request left over from a prior,
 * already-torn-down run of that same chat.
 */
data class ToolApprovalRequest(
  val requestId: String,
  val runId: String,
  val conversationId: String,
  val toolName: String,
  val riskClass: RiskClass,
  val arguments: Map<String, JsonElement>,
)

/**
 * What the harness does about one tool call, decided once per call by [ExecutionPolicy.evaluate].
 * [com.aiopenpocket.agent.loop.ReactLoopRunner] is the sole interpreter: every branch here maps to
 * exactly one thing it does before/instead of calling [com.aiopenpocket.agent.core.mcp.ToolExecutor].
 */
sealed interface PolicyDecision {
  /** Run the tool for real, exactly like every call before Task 9. */
  data object Execute : PolicyDecision

  /** Don't touch real state — hand the model a synthetic "not executed" result instead ([reason] is for logs/telemetry, not shown to the model). */
  data class Simulate(val reason: String) : PolicyDecision

  /** Never run — the caller gets a [com.aiopenpocket.agent.core.mcp.ToolResult.Error] with [reason] as the message. */
  data class Deny(val reason: String) : PolicyDecision

  /** Suspend on [ToolApprovalCoordinator] for [request] before deciding Execute-or-Deny. */
  data class AwaitApproval(val request: ToolApprovalRequest) : PolicyDecision
}

/**
 * Pure evaluator (design spec section 9 / task-9-brief.md Step 1-2): given a call's [ExecutionMode],
 * its actual per-call [RiskClass] ([com.aiopenpocket.agent.core.mcp.Tool.riskFor]) and the
 * [HookDecision] [com.aiopenpocket.agent.core.hook.HookEngine] already computed for `BEFORE_TOOL`,
 * decides once and for all what happens to this specific tool call. No I/O, no suspend, no randomness —
 * [requestId] is generated by the caller (typically `UUID.randomUUID()`) precisely so this function
 * itself stays 100% deterministic and trivially testable.
 *
 * "Agent policy" (the design brief's third input, alongside mode/risk/hookDecision) has no separate
 * field on `AgentDefinition` today — the only per-agent rule that exists is its hooks, and those are
 * already folded into [hookDecision] by the time this runs. So the brief's "LIVE + risky → agent rule,
 * never weaker than the global safety floor" resolves to: a hook may DENY or REQUIRE_APPROVAL a call
 * (checked first, below — that floor can never be relaxed by mode or risk), and absent either, LIVE's
 * un-configurable floor is simply Execute, identical to every pre-Task-9 call. If a richer per-agent
 * policy is ever added, it plugs in here without changing this function's contract.
 *
 * Hook DENY/REQUIRE_APPROVAL are checked BEFORE the mode/risk table and win unconditionally, in both
 * LIVE and PREVIEW — a hook that blocks a tool must actually block it during a preview run too, not get
 * silently downgraded to a Simulate that looks like a harmless no-op for a different reason.
 */
object ExecutionPolicy {

  fun evaluate(
    mode: ExecutionMode,
    risk: RiskClass,
    hookDecision: HookDecision,
    toolName: String,
    arguments: Map<String, JsonElement>,
    runId: String,
    requestId: String,
    conversationId: String,
  ): PolicyDecision {
    if (hookDecision.denied) {
      return PolicyDecision.Deny("Tool '$toolName' was denied by an agent hook.")
    }
    if (hookDecision.approvalRequired) {
      return PolicyDecision.AwaitApproval(
        ToolApprovalRequest(
          requestId = requestId,
          runId = runId,
          conversationId = conversationId,
          toolName = toolName,
          riskClass = risk,
          arguments = arguments,
        ),
      )
    }
    return when (mode) {
      ExecutionMode.LIVE -> PolicyDecision.Execute
      ExecutionMode.PREVIEW -> when (risk) {
        RiskClass.READ -> PolicyDecision.Execute
        RiskClass.WRITE, RiskClass.DESTRUCTIVE, RiskClass.EXTERNAL ->
          PolicyDecision.Simulate("Preview mode: '$toolName' ($risk) was not executed.")
      }
    }
  }
}

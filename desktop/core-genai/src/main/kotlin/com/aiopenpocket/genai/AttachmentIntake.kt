package com.aiopenpocket.genai

// @trace desktop-genai-client-4c63b6

import java.io.File

/**
 * Единственная калитка, через которую файл попадает во вложения.
 *
 * Появилась после того, как рядом с системным диалогом выбора возникла зона перетаскивания. Диалог
 * хотя бы делал вид, что фильтрует по расширению, — а бросить в окно можно что угодно: `.mp4`,
 * папку, гигабайтный `.psd`. Дальше такой файл шёл ровно тем же путём, что картинка:
 * [imageFileToDataUrl] не проверяет ничего, [mimeByExtension] на незнакомом расширении отдаёт
 * `application/octet-stream`, и мусор уезжал в ПЛАТНЫЙ запрос как `image_url`. Модель отвечала 200
 * без картинки, задание падало, деньги списывались. Молча отправить заведомо негодный файл за деньги
 * — то же враньё про деньги, от которого бережёт [CostSummary.partial], только дороже.
 *
 * Оговорка про диалог: его `setFilenameFilter` на Windows не работает вовсе (AWT игнорирует фильтр
 * на этой платформе), так что проверять надо оба пути, а не только перетаскивание.
 *
 * Возвращает причину отказа для показа пользователю или `null`, если файл годится. Причина текстом,
 * а не кодом: вариантов три, и заводить под них иерархию типов дороже, чем оно стоит.
 */
fun rejectionReason(file: File, maxBytes: Long = MAX_INPUT_BYTES): String? = when {
  file.isDirectory -> "это папка, а не файл"
  !file.isFile -> "файл не найден"
  mimeByExtension(file.name) == FALLBACK_MIME ->
    "формат не поддерживается — нужен ${SUPPORTED_EXTENSIONS.joinToString(", ")}"
  // Размер проверяем ДО чтения: imageFileToDataUrl зовёт readBytes(), а тот на большом файле кидает
  // OutOfMemoryError — это Error, а не Exception, и он проходит мимо catch в GenerationQueue.
  // Задание тогда не падает, а навсегда виснет в RUNNING.
  file.length() > maxBytes -> "файл больше ${maxBytes / 1024 / 1024} МБ"
  else -> null
}

/**
 * Потолок размера входной картинки.
 *
 * Взят не из ограничений OpenRouter (их он не публикует), а из арифметики: файл читается целиком в
 * память и раздувается base64 примерно на треть, и делается это дважды — один раз ради миниатюры
 * 44dp в карточке, второй раз перед запросом. 20 МБ на диске — это уже под 60 МБ живой памяти на
 * одно вложение, а их бывает пять.
 */
const val MAX_INPUT_BYTES: Long = 20L * 1024 * 1024

internal const val FALLBACK_MIME = "application/octet-stream"

internal val SUPPORTED_EXTENSIONS = listOf("png", "jpg", "jpeg", "webp", "gif")
